import type { StandardCategory, StudyCefrLevel, VocabularyItem } from "../types/vocabulary";
import { slugify } from "./slug";

function item(
  category: StandardCategory,
  term: string,
  translation: string,
  difficulty: StudyCefrLevel = "A1",
): VocabularyItem {
  return {
    id: `eu-${category.replace(/s$/, "")}-${slugify(term)}`,
    category,
    term,
    translation,
    difficulty,
    tags: difficulty === "A1" || difficulty === "A2" || difficulty === "B1" ? undefined : [CEFR_LOCK_TAG],
  };
}

