function item(
  category: StandardCategory,
  term: string,
  translation: string,
  difficulty: StudyCefrLevel = "A1",
  extras: Partial<Pick<VocabularyItem, "example" | "exampleTranslation">> = {},
): VocabularyItem {
  return {
    id: `ca-${category.replace(/s$/, "")}-${slugify(term)}`,
    category,
    term,
    translation,
    difficulty,
    tags: difficulty === "A1" || difficulty === "A2" || difficulty === "B1" ? undefined : [CEFR_LOCK_TAG],
    ...extras,
  };
}

