function item(
  category: StandardCategory,
  term: string,
  translation: string,
  extras: Partial<Pick<VocabularyItem, "example" | "exampleTranslation" | "difficulty">> = {},
): VocabularyItem {
  return {
    id: `fr-${category.replace(/s$/, "")}-${slugify(term)}`,
    category,
    term,
    translation,
    difficulty: extras.difficulty ?? "A1",
    ...extras,
  };
}

