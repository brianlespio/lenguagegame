import type { VerbItem } from "../types/vocabulary";

function verb(
  infinitive: string,
  past: string,
  pastParticiple: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
  regularity: "regular" | "irregular",
): VerbItem {
  return {
    id: `verb-${infinitive}`,
    category: "verbs",
    infinitive,
    past,
    pastParticiple,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    difficulty: "A1",
    tags: [regularity],
  };
}

function irr(
  infinitive: string,
  past: string,
  pastParticiple: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
): VerbItem {
  return verb(
    infinitive,
    past,
    pastParticiple,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    "irregular",
  );
}

function reg(
  infinitive: string,
  past: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
): VerbItem {
  return verb(
    infinitive,
    past,
    past,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    "regular",
  );
}

