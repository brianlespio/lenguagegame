import type { VerbItem } from "../types/vocabulary";
import { slugify } from "./slug";

function verb(
  infinitive: string,
  past: string,
  pastParticiple: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
  auxiliary: "avoir" | "etre",
): VerbItem {
  return {
    id: `fr-verb-${slugify(infinitive)}`,
    category: "verbs",
    infinitive,
    past,
    pastParticiple,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    difficulty: "A1",
    tags: [auxiliary === "etre" ? "auxiliary-etre" : "auxiliary-avoir"],
  };
}

function er(
  infinitive: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
): VerbItem {
  const pastParticiple = infinitive.replace(/er$/, "é");
  return verb(
    infinitive,
    `a ${pastParticiple}`,
    pastParticiple,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    "avoir",
  );
}

function ir2(
  infinitive: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
): VerbItem {
  const pastParticiple = infinitive.replace(/ir$/, "i");
  return verb(
    infinitive,
    `a ${pastParticiple}`,
    pastParticiple,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    "avoir",
  );
}

function reReg(
  infinitive: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
): VerbItem {
  const pastParticiple = infinitive.replace(/re$/, "u");
  return verb(
    infinitive,
    `a ${pastParticiple}`,
    pastParticiple,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    "avoir",
  );
}

function irr(
  infinitive: string,
  past: string,
  pastParticiple: string,
  infinitiveTranslation: string,
  pastTranslation: string,
  pastParticipleTranslation: string,
  auxiliary: "avoir" | "etre" = "avoir",
): VerbItem {
  return verb(
    infinitive,
    past,
    pastParticiple,
    infinitiveTranslation,
    pastTranslation,
    pastParticipleTranslation,
    auxiliary,
  );
}

