const REVIEWED_SIGMOID_W = [1, 2, 4] as const;
export type SigmoidW = (typeof REVIEWED_SIGMOID_W)[number];

const REVIEWED_LOSSES = [
  { id: "calc-loss-linear", w: 1, x: 2, y: 1 },
  { id: "calc-loss-w0-x3-y1", w: 0, x: 3, y: 1 },
] as const;

export type LossCase = (typeof REVIEWED_LOSSES)[number];

export function sigmoidChainCard(w: SigmoidW): MathCard {
  if (!REVIEWED_SIGMOID_W.includes(w)) {
    throw new Error(`w=${w} no está en la plantilla revisada de σ(wx).`);
  }
  const fPrime = w / 4;
  const tangent =
    fPrime === 1 ? "y = 1/2 + x" : fPrime === 0.5 ? "y = 1/2 + (1/2) x" : "y = 1/2 + (1/4) x";
  const answer =
    fPrime === 1 ? "1" : fPrime === 0.5 ? "0.5" : "0.25";
  return makeCard({
    id: w === 2 ? "calc-chain-sigmoid" : `calc-chain-sigmoid-w${w}`,
    axis: "calculus",
    level: "L2",
    kind: "decomposition",
    object: "Regla de la cadena",
    title: `σ(${w}x)`,
    face: `f(x) = σ(${w}x), con σ(u) = 1 / (1 + e^(−u)). Mira el punto x = 0.`,
    answer: `f(0) = 1/2 y f'(0) = ${answer}. La cadena es σ'(0) · ${w} = (1/4) · ${w}.`,
    definition: "Si f = g ∘ h, la pendiente de f es la pendiente de g en h(x), por la pendiente de h.",
    example: `h(0) = 0, σ(0) = 1/2, σ'(0) = (1/2)·(1/2) = 1/4, f'(0) = (1/4)·${w} = ${answer}.`,
    whyAi: "Una neurona es exactamente esto: una recta wx + b y luego una sigmoide. Sin la cadena, el peso no se entera del error.",
    trap: "Derivar σ(wx) como si w fuera la derivada de σ, y olvidar multiplicar por w.",
    steps: [
      `h(x) = ${w}x`,
      "g(u) = σ(u) = 1 / (1 + e^(−u))",
      "h(0) = 0 y σ(0) = 1/2",
      "σ'(0) = σ(0)·(1 − σ(0)) = 1/4",
      `f'(0) = (1/4) · ${w} = ${answer}`,
    ],
    step: {
      ask: "Escribe f'(0)",
      expect: answer,
      accept: answer === "0.5" ? ["1/2", "0.50"] : answer === "0.25" ? ["1/4"] : ["1.0"],
    },
    decomposition: {
      expression: `σ(${w}x)`,
      relation: "compose",
      g: "σ(u) = 1/(1+e^(−u))",
      h: `${w}x`,
      x0: 0,
      hAt: 0,
      gAt: 0.5,
      fAt: 0.5,
      gPrimeAt: 0.25,
      hPrimeAt: w,
      fPrimeAt: fPrime,
      tangent,
    },
    plotId: `sigmoid-w${w}`,
    quizForward: `f(x) = σ(${w}x). ¿Cuánto vale f'(0)? σ'(0) = 1/4.`,
    quizForwardAnswer: answer,
    quizReverse: `La pendiente en 0 es ${answer} y h(x) = ${w}x, g = σ. ¿Qué función es f?`,
    quizReverseAnswer: `σ(${w}x)`,
  });
}

export function lossCard(spec: LossCase): MathCard {
  const known = REVIEWED_LOSSES.find((item) => item.id === spec.id && item.w === spec.w && item.x === spec.x && item.y === spec.y);
  if (!known) {
    throw new Error("Esa terna (w, x, y) no está en la plantilla revisada de la pérdida.");
  }
  const hAt = spec.x * spec.w - spec.y;
  const fAt = hAt * hAt;
  const fPrime = 2 * hAt * spec.x;
  const answer = String(fPrime);
  return makeCard({
    id: spec.id,
    axis: "calculus",
    level: "L2",
    kind: "decomposition",
    object: "Pérdida cuadrática",
    title: `L = (ŷ − y)² con ŷ = ${spec.x}w`,
    face: `y = ${spec.y}, x = ${spec.x}, w = ${spec.w}. ŷ = xw. L(w) = (xw − y)². Calcula dL/dw en ese w.`,
    answer: `dL/dw = 2(xw − y) x = 2(${spec.x * spec.w} − ${spec.y}) · ${spec.x} = ${answer}.`,
    definition: "La pérdida mide cuánto se aleja la predicción del dato. Su derivada respecto a w dice si subir w empeora o mejora.",
    example: `h(w) = ${spec.x}w − ${spec.y}. En w = ${spec.w}, h = ${hAt}, L = ${fAt}, h' = ${spec.x}, g'(h) = ${2 * hAt}.`,
    whyAi: "Entrenar es mover w para bajar L. El signo de dL/dw es la decisión: subir o bajar el peso.",
    trap: "Olvidar el factor x al pasar de dL/dŷ a dL/dw. La cadena tiene dos piezas, no una.",
    steps: [
      `ŷ = ${spec.x} · ${spec.w} = ${spec.x * spec.w}`,
      `L = (${spec.x * spec.w} − ${spec.y})² = ${fAt}`,
      `dL/dŷ = 2(ŷ − y) = ${2 * hAt}`,
      `dL/dw = 2(xw − y) · x = ${answer}`,
    ],
    step: { ask: "Escribe dL/dw", expect: answer, accept: [String(fPrime)] },
    decomposition: {
      expression: `L(w) = (${spec.x}w − ${spec.y})²`,
      relation: "compose",
      g: "u²",
      h: `${spec.x}w − ${spec.y}`,
      x0: spec.w,
      hAt,
      gAt: fAt,
      fAt,
      gPrimeAt: 2 * hAt,
      hPrimeAt: spec.x,
      fPrimeAt: fPrime,
      tangent: `L ≈ ${fAt} + (${answer})(w − ${spec.w})`,
    },
    plotId: spec.x === 2 ? "loss-x2-y1" : "loss-x3-y1",
    quizForward: `L = (xw − y)² con x = ${spec.x}, y = ${spec.y}, w = ${spec.w}. ¿dL/dw?`,
    quizForwardAnswer: answer,
    quizReverse: `dL/dw = ${answer} con x = ${spec.x}, y = ${spec.y}, w = ${spec.w}. ¿Qué pérdida es?`,
    quizReverseAnswer: `(${spec.x}w − ${spec.y})²`,
  });
}

