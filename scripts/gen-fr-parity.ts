function pickVerbs(need: number) {
  const out: typeof verbs = [];
  const seen = new Set<string>();
  for (const v of verbs) {
    const key = v.inf.toLowerCase();
    if (taken.has(key) || seen.has(key)) continue;
    // skip broken helpers that aren't real French verbs
    if (key === "ventilateur" || key === "calendrier" || key === "messager" || key === "mandatier" || key === "stockager" || key === "requeter" || key === "courrieller" || key === "échéanceer" || key === "hasher") continue;
    if (key.includes(" ")) continue; // compound infinitives complicate id/slug; skip for safety
    seen.add(key);
    out.push(v);
    if (out.length >= need) break;
  }
  if (out.length < need) {
    throw new Error(`verbs: need ${need}, only found ${out.length}`);
  }
  return out;
}

