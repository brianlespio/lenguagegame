type Pair = readonly [string, string];

const taken = new Set<string>();
for (const entry of frenchEntries) {
  if (isVerbItem(entry)) taken.add(entry.infinitive.toLowerCase());
  else taken.add(entry.term.toLowerCase());
}

function pick(pairs: Pair[], need: number, label: string): Pair[] {
  const out: Pair[] = [];
  const seen = new Set<string>();
  for (const [term, tr] of pairs) {
    const key = term.toLowerCase();
    if (taken.has(key) || seen.has(key)) continue;
    seen.add(key);
    out.push([term, tr]);
    if (out.length >= need) break;
  }
  if (out.length < need) {
    throw new Error(`${label}: need ${need}, only found ${out.length} free terms`);
  }
  return out;
}

