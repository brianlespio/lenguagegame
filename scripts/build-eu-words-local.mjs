function matchCase(src, dest) {
  if (!src || !dest) return dest;
  if (src === src.toUpperCase()) return dest.toUpperCase();
  if (src[0] === src[0]?.toUpperCase()) return dest.charAt(0).toUpperCase() + dest.slice(1);
  return dest;
}

