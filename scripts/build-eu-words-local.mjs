function lookup(es, cat) {
  const key = es.trim().toLowerCase();
  if (cat && CAT_OVR[cat]?.[key]) return CAT_OVR[cat][key];
  if (ES_EU[key]) return ES_EU[key];
  if (key.includes("/")) {
    for (const part of key.split("/")) {
      const p = part.trim();
      if (cat && CAT_OVR[cat]?.[p]) return CAT_OVR[cat][p];
      if (ES_EU[p]) return ES_EU[p];
    }
  }
  return null;
}

function esToEu(es, cat) {
  const raw = es.trim();
  if (!raw) return "";
  const hit = lookup(raw, cat);
  if (hit) return hit;

  if (/\s/.test(raw) || raw.includes("/")) {
    const parts = raw.split(/(\s+|\/)/);
    const out = [];
    for (const part of parts) {
      if (/^\s+$/.test(part) || part === "/") {
        out.push(part === "/" ? "/" : " ");
        continue;
      }
      const low = part.toLowerCase();
      const mapped = lookup(part, cat);
      if (mapped) {
        out.push(mapped);
        continue;
      }
      if (Object.prototype.hasOwnProperty.call(FUNC, low)) {
        const f = FUNC[low];
        if (f === "") continue;
        out.push(f);
        continue;
      }
      out.push(matchCase(part, adaptLoan(part)));
    }
    return out.join("").replace(/\s+/g, " ").trim().replace(/^\/+|\/+$/g, "");
  }

  return matchCase(raw, adaptLoan(raw));
}

